#!/usr/bin/env node
// Builds src/data.js — the plate catalog and the wall model the page runs on —
// from the artist's source files in space_and_plates/.
//
//   node tools/build-data.mjs
//
// Needs `mutool` (MuPDF) on the PATH to read the Illustrator files. The output
// is generated; edit the sources or this pipeline, never src/data.js.
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { plateFromSvg, plateIdFromFilename } from "./plates.mjs";
import { parseWall } from "./wall.mjs";

const run = promisify(execFile);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "space_and_plates");
const OUTPUT = join(root, "src", "data.js");
const FAMILIES = ["A", "T", "C", "G"];
const PLATES_PER_FAMILY = 75;

async function svgOf(file) {
  try {
    const { stdout } = await run("mutool", ["draw", "-q", "-F", "svg", "-o", "-", file, "1"],
      { maxBuffer: 64 * 1024 * 1024 });
    return stdout;
  } catch (err) {
    if (err.code === "ENOENT") throw new Error("mutool not found. Install MuPDF (brew install mupdf).");
    throw err;
  }
}

const plates = [];
for (const family of FAMILIES) {
  const dir = join(SOURCE, `${family}_vectors`);
  const files = (await readdir(dir)).filter((f) => /\.ai$/i.test(f))
    .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
  if (files.length !== PLATES_PER_FAMILY) {
    throw new Error(`Family ${family}: expected ${PLATES_PER_FAMILY} plates, found ${files.length}.`);
  }
  for (const file of files) {
    try {
      plates.push(plateFromSvg(await svgOf(join(dir, file)), {
        id: plateIdFromFilename(file), family, source: `${family}_vectors/${file}`,
      }));
    } catch (err) {
      throw new Error(`${family}_vectors/${file}: ${err.message}`);
    }
  }
  console.error(`  ${family}  ${files.length} plates`);
}
const ids = new Set(plates.map((p) => p.id));
if (ids.size !== plates.length) throw new Error("Plate IDs are not unique.");

const models = (await readdir(SOURCE)).filter((f) => /\.obj$/i.test(f));
if (models.length !== 1) throw new Error(`Expected one .obj wall model in space_and_plates/, found ${models.length}.`);
const wall = parseWall(await readFile(join(SOURCE, models[0]), "latin1"));
console.error(`  wall  ${wall.width} × ${wall.height} ${wall.units}, ${wall.walls.length} walls, ${wall.nails.length} nails`);

const json = JSON.stringify({ wall, plates });
await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT,
  "// Generated by tools/build-data.mjs from space_and_plates/. Do not edit.\n" +
  `window.OUIJATARI_DATA = ${json};\n`);
console.error(`\nWrote src/data.js (${(Buffer.byteLength(json) / 1024).toFixed(0)} kB).`);
